import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const octicons = createRequire(import.meta.url)("@primer/octicons");
const map = {
  plus: "plus", folder: "file-directory", chat: "comment-discussion", star: "star", grid: "plug",
  mic: "unmute", back: "arrow-left", home: "home", left: "chevron-left", right: "chevron-right",
  refresh: "sync", open: "mark-github", check: "check", pin: "pin", error: "alert", session: "pulse", attention: "bell", copilot: "copilot", sparkle: "sparkle-fill", server: "server",
};
const entries = Object.entries(map).map(([key, name]) => {
  const icon = octicons[name];
  if (!icon?.heights?.[24]) throw new Error(`Missing 24px octicon ${name}`);
  const markup = icon.heights[24].path;
  const parts = [...markup.matchAll(/<path d="([^"<>]+)"(?: fill-rule="evenodd")?><\/path>/g)];
  if (!parts.length || parts.map((part) => part[0]).join("") !== markup) throw new Error(`Octicon ${name} has unsupported markup`);
  return `  ${key}: ${JSON.stringify(parts.map((part) => part[1]))},`;
});
await writeFile("src/plugin/icons.ts", `// Generated by scripts/gen-icons.mjs from @primer/octicons (MIT License, Copyright GitHub Inc.). Do not edit.
export const icons = {
${entries.join("\n")}
} as const;
`);
console.log(`Wrote ${entries.length} icons to src/plugin/icons.ts`);
